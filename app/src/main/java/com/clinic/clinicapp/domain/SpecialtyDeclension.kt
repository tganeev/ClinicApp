package com.clinic.clinicapp.domain

/**
 * Склонение специальностей врачей для озвучки через TTS.
 *
 * Нужно потому, что TTS читает «к Кардиолог» как «к Кардиолог» (именительный),
 * а нам нужно «к кардиологу» (дательный падеж).
 *
 * Словарь ручной — универсального правила для всех специальностей нет.
 */
object SpecialtyDeclension {

    /** Специальность → предложный/дательный падеж для фразы «к ...» */
    private val dativeForms = mapOf(
        "Терапевт" to "терапевту",
        "Кардиолог" to "кардиологу",
        "Невролог" to "неврологу",
        "Стоматолог" to "стоматологу",
        "Дерматолог" to "дерматологу",
        "Гинеколог" to "гинекологу",
        "Офтальмолог" to "офтальмологу",
        "Психолог" to "психологу",
        "Психотерапевт" to "психотерапевту",
        "Хирург" to "хирургу",
        "ЛОР" to "лору",
        "Эндокринолог" to "эндокринологу",
        "Уролог" to "урологу",
        "Онколог" to "онкологу",
        "Педиатр" to "педиатру"
    )

    /**
     * Возвращает специальность в дательном падеже («к кому?»).
     * Если специальность не найдена в словаре — возвращает как есть.
     */
    fun toDative(specialty: String): String {
        return dativeForms[specialty]
            ?: dativeForms.entries
                .firstOrNull { it.key.equals(specialty, ignoreCase = true) }
                ?.value
            ?: specialty
    }

    /**
     * Возвращает специальность в родительном падеже («у кого?»).
     * Пока используем ту же форму, что и дательный — этого достаточно
     * для озвучки «у врача-кардиолога».
     */
    fun toGenitive(specialty: String): String = toDative(specialty)
}