package com.clinic.clinicapp.domain

import java.time.LocalDate
import java.time.LocalTime

/**
 * Форматирует дату и время в человекочитаемый русский текст для TTS.
 *
 * Нужно потому, что TTS плохо читает ISO-даты и 24-часовое время:
 *   "2026-10-10" читается как «две тысячи двадцать шесть десять десять»,
 *   "09:00" читается как «ноль девять ноль ноль».
 *
 * Здесь мы превращаем их в:
 *   "десятое октября" и "девять часов утра".
 */
object RussianDateFormatter {

    private val monthNamesGenitive = listOf(
        "января", "февраля", "марта", "апреля", "мая", "июня",
        "июля", "августа", "сентября", "октября", "ноября", "декабря"
    )

    /** Даты в родительном падеже: "первое", "второе", ..., "тридцать первое" */
    private val dayOrdinals = listOf(
        "первое", "второе", "третье", "четвёртое", "пятое",
        "шестое", "седьмое", "восьмое", "девятое", "десятое",
        "одиннадцатое", "двенадцатое", "тринадцатое", "четырнадцатое", "пятнадцатое",
        "шестнадцатое", "семнадцатое", "восемнадцатое", "девятнадцатое", "двадцатое",
        "двадцать первое", "двадцать второе", "двадцать третье", "двадцать четвёртое", "двадцать пятое",
        "двадцать шестое", "двадцать седьмое", "двадцать восьмое", "двадцать девятое", "тридцатое",
        "тридцать первое"
    )

    /** Часы в именительном падеже: "один час", "два часа", ..., "двенадцать часов" */
    private val hourWords = listOf(
        "ноль", "один", "два", "три", "четыре", "пять",
        "шесть", "семь", "восемь", "девять", "десять",
        "одиннадцать", "двенадцать"
    )

    /**
     * Форматирует дату ISO ("2026-10-10") в человекочитаемый вид:
     * "десятое октября" или "десятое октября две тысячи двадцать шесть".
     *
     * @param isoDate дата в формате "yyyy-MM-dd"
     * @param includeYear добавлять ли год (по умолчанию true, но для ближайших дат можно опустить)
     */
    fun formatDate(isoDate: String, includeYear: Boolean = false): String {
        return try {
            val date = LocalDate.parse(isoDate)
            val day = dayOrdinals.getOrNull(date.dayOfMonth - 1) ?: date.dayOfMonth.toString()
            val month = monthNamesGenitive.getOrNull(date.monthValue - 1) ?: ""
            val base = "$day $month"
            if (includeYear) {
                "$base ${formatYear(date.year)}"
            } else {
                base
            }
        } catch (t: Throwable) {
            isoDate
        }
    }

    /**
     * Форматирует время ISO ("09:00", "15:30") в человекочитаемый вид:
     * "девять часов утра" / "три часа дня" / "полчетвёртого" / "половина третьего".
     */
    fun formatTime(isoTime: String): String {
        return try {
            val time = LocalTime.parse(isoTime)
            val hour = time.hour
            val minute = time.minute

            when {
                minute == 0 -> {
                    val hour12 = to12Hour(hour)
                    val period = getPeriod(hour)
                    "$hour12 часов $period"
                }
                minute == 30 -> {
                    // "половина третьего" — сложно для 12-часового формата.
                    // Проще: "два часа тридцать минут дня".
                    val hour12 = to12Hour(hour)
                    val period = getPeriod(hour)
                    "$hour12 часов тридцать минут $period"
                }
                else -> {
                    val hour12 = to12Hour(hour)
                    val period = getPeriod(hour)
                    val minuteWord = formatMinute(minute)
                    "$hour12 часов $minuteWord $period"
                }
            }
        } catch (t: Throwable) {
            isoTime
        }
    }

    /** 0..23 → 12-часовой формат (1..12). */
    private fun to12Hour(hour24: Int): String {
        val hour12 = when {
            hour24 == 0 -> 12
            hour24 <= 12 -> hour24
            else -> hour24 - 12
        }
        return hourWords.getOrNull(hour12) ?: hour12.toString()
    }

    /** Определяет период дня: утра, дня, вечера, ночи. */
    private fun getPeriod(hour24: Int): String {
        return when (hour24) {
            in 0..4 -> "ночи"
            in 5..11 -> "утра"
            in 12..17 -> "дня"
            in 18..23 -> "вечера"
            else -> ""
        }
    }

    private fun formatMinute(minute: Int): String {
        val words = listOf(
            "", "одна минута", "две минуты", "три минуты", "четыре минуты",
            "пять минут", "шесть минут", "семь минут", "восемь минут", "девять минут",
            "десять минут", "одиннадцать минут", "двенадцать минут", "тринадцать минут", "четырнадцать минут",
            "пятнадцать минут", "шестнадцать минут", "семнадцать минут", "восемнадцать минут", "девятнадцать минут",
            "двадцать минут", "двадцать одна минута", "двадцать две минуты", "двадцать три минуты",
            "двадцать четыре минуты", "двадцать пять минут", "двадцать шесть минут", "двадцать семь минут",
            "двадцать восемь минут", "двадцать девять минут", "тридцать минут",
            "тридцать одна минута", "тридцать две минуты", "тридцать три минуты", "тридцать четыре минуты",
            "тридцать пять минут", "тридцать шесть минут", "тридцать семь минут", "тридцать восемь минут",
            "тридцать девять минут", "сорок минут", "сорок одна минута", "сорок две минуты",
            "сорок три минуты", "сорок четыре минуты", "сорок пять минут", "сорок шесть минут",
            "сорок семь минут", "сорок восемь минут", "сорок девять минут", "пятьдесят минут",
            "пятьдесят одна минута", "пятьдесят две минуты", "пятьдесят три минуты",
            "пятьдесят четыре минуты", "пятьдесят пять минут", "пятьдесят шесть минут",
            "пятьдесят семь минут", "пятьдесят восемь минут", "пятьдесят девять минут"
        )
        return words.getOrNull(minute) ?: "$minute минут"
    }

    /** Форматирует год: 2026 → "две тысячи двадцать шесть". */
    private fun formatYear(year: Int): String {
        val thousands = year / 1000
        val hundreds = (year / 100) % 10
        val tens = (year / 10) % 10
        val ones = year % 10

        val sb = StringBuilder()

        // Тысячи
        when (thousands) {
            1 -> sb.append("одна тысяча ")
            2 -> sb.append("две тысячи ")
            3 -> sb.append("три тысячи ")
            4 -> sb.append("четыре тысячи ")
            5 -> sb.append("пять тысяч ")
            else -> sb.append("$thousands тысяч ")
        }

        // Сотни
        val hundredWords = listOf("", "сто", "двести", "триста", "четыреста",
            "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот")
        if (hundreds > 0) sb.append("${hundredWords[hundreds]} ")

        // Десятки
        val tensWords = listOf("", "", "двадцать", "тридцать", "сорок",
            "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто")
        if (tens >= 2) sb.append("${tensWords[tens]} ")

        // Единицы
        if (tens == 1) {
            // 10..19
            val teenWords = listOf("десять", "одиннадцать", "двенадцать", "тринадцать",
                "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать")
            sb.append(teenWords[ones])
        } else if (ones > 0) {
            val onesWords = listOf("", "один", "два", "три", "четыре",
                "пять", "шесть", "семь", "восемь", "девять")
            sb.append(onesWords[ones])
        }

        return sb.toString().trim()
    }
}